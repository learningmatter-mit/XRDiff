#!/bin/bash
# rank20.sh — the paper evaluation: generate 20 candidates per RRUFF-148
# sample, rank them by pre-aligned Rietveld refinement against the measured
# pattern (config_align.yaml protocol), report success@1/@3/@10 of the ranked list.
#
#   bash scripts/rruff_eval/rank20.sh MODEL_DIR EVAL_DATASET VARIANT [GPU_PARTITION]
#
#   MODEL_DIR     folder with the checkpoint, hparams.yaml and scalers (absolute path)
#   EVAL_DATASET  rruff_pv (full-spectrum models) | rruff_pv_peaks (peaks models)
#   VARIANT       a short unique name for this model (config key, output label)
#   GPU_PARTITION xeon-g6-volta (default) | jupyter-gpu
#
# Submits two chained jobs:
#   1. GPU: evaluate.py --num_evals=20, then compute_metrics.py (official coverage@20)
#   2. CPU (xeon-p8): prepare.py -> refine.py -> analyze.py -> report.py
# Writes scripts/rruff_eval/configs/VARIANT.yaml; results in MODEL_DIR/rietveld_ranking/align_k20/,
# with the paper numbers in rank20_report.txt there.
set -e
MODEL_DIR=$1; DS=$2; VARIANT=$3; PART=${4:-xeon-g6-volta}
[ -d "$MODEL_DIR" ] && [ -n "$DS" ] && [ -n "$VARIANT" ] || { echo "usage: $0 MODEL_DIR EVAL_DATASET VARIANT [GPU_PARTITION]"; exit 1; }
ROOT=$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)
CFG_DIR=$ROOT/scripts/rruff_eval/configs; mkdir -p $CFG_DIR $ROOT/out/jobs/rank20
CFG=$CFG_DIR/$VARIANT.yaml
cat > $CFG <<EOF
# Generated by rank20.sh: 20 candidates per sample, pre-aligned Rietveld ranking.
base: ../../rietveld_ranking/config_align.yaml
run_dirs: {$VARIANT: $MODEL_DIR}
gen_files: {20: eval_diff_${DS}_n_evals_20.pt}
metrics_files: {20: eval_metrics_${DS}_n_evals_20.json}
output_subdir: rietveld_ranking/align_k20
EOF
HDR="source /etc/profile; source \$HOME/.bashrc; export PROJECT_ROOT=$ROOT; cd $ROOT; set -ex"
G=$(sbatch --parsable --job-name=gen20_$VARIANT --partition=$PART --nodes=1 --gres=gpu:volta:1 --mem=300G \
     --cpus-per-task=20 --time=0-12:00:00 --output=$ROOT/out/jobs/rank20/gen_$VARIANT.out --error=$ROOT/out/jobs/rank20/gen_$VARIANT.err \
     --wrap="$HDR; python scripts/evaluation/evaluate.py --model_path=$MODEL_DIR --eval_dataset=$DS --num_evals=20; \
             python scripts/evaluation/compute_metrics.py --root_path=$MODEL_DIR --label=${DS}_n_evals_20 --multi_eval")
R=$(sbatch --parsable --dependency=afterok:$G --job-name=rank20_$VARIANT --partition=xeon-p8 --nodes=1 --cpus-per-task=48 \
     --mem=150GB --time=2-00:00:00 --output=$ROOT/out/jobs/rank20/rank_$VARIANT.out --error=$ROOT/out/jobs/rank20/rank_$VARIANT.err \
     --wrap="$HDR; for s in prepare refine analyze; do extra=''; [ \$s = refine ] && extra=--force; \
             python scripts/rietveld_ranking/\$s.py --config $CFG --variant $VARIANT \$extra; done; \
             python scripts/rruff_eval/report.py --config $CFG --variant $VARIANT")
echo "$VARIANT: generation $G -> ranking $R  (config $CFG)"
